#!/usr/bin/env bash
# Moonlight binary build (Linux) — uses Nuitka.
# Output: dist/moonlight-linux-<date>/ folder ready to zip and distribute.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT"

# ---------- stamp build metadata ----------
# Required env vars for centralized revocation:
#   MOONLIGHT_REVOCATION_REPO   e.g. "krisk248/moonlight-revocations"
#   MOONLIGHT_REVOCATION_PAT    fine-grained read-only PAT for that repo
# (Optional)
#   MOONLIGHT_REVOCATION_FILE   defaults to "revoked.json"
if [[ -z "${MOONLIGHT_REVOCATION_REPO:-}" || -z "${MOONLIGHT_REVOCATION_PAT:-}" ]]; then
    echo "[build] WARNING: MOONLIGHT_REVOCATION_REPO and MOONLIGHT_REVOCATION_PAT not set."
    echo "[build] Building WITHOUT centralized revocation. Binary will run unrestricted."
    REVOCATION_REPO=""
    REVOCATION_PAT=""
else
    REVOCATION_REPO="$MOONLIGHT_REVOCATION_REPO"
    REVOCATION_PAT="$MOONLIGHT_REVOCATION_PAT"
fi
REVOCATION_FILE="${MOONLIGHT_REVOCATION_FILE:-revoked.json}"

BUILD_DATE="$(date -u +%Y-%m-%d)"
BUILD_ID="ml-$BUILD_DATE-$(head -c4 /dev/urandom | xxd -p)"
VERSION="$(grep -E '^version' pyproject.toml | head -1 | sed 's/.*"\(.*\)".*/\1/')"

cat > src/moonlight/_buildinfo.py <<EOF
"""Build-time stamped constants. Do not edit by hand."""
BUILD_DATE = "$BUILD_DATE"
BUILD_ID = "$BUILD_ID"
VERSION = "$VERSION"
REVOCATION_REPO = "$REVOCATION_REPO"
REVOCATION_FILE = "$REVOCATION_FILE"
REVOCATION_PAT = "$REVOCATION_PAT"
EOF
echo "[build] stamped build $BUILD_ID"

# ---------- prep environment ----------
uv sync
uv add --dev nuitka >/dev/null 2>&1 || true

# Ensure Playwright Chromium is present (we'll ship it alongside the binary)
uv run playwright install chromium

OUT_DIR="dist/moonlight-linux-$BUILD_DATE"
rm -rf "$OUT_DIR"
mkdir -p "$OUT_DIR"

# ---------- Nuitka compile ----------
echo "[build] compiling with Nuitka (5-10 min)..."
uv run python -m nuitka \
    --standalone \
    --output-dir="$OUT_DIR" \
    --output-filename=moonlight \
    --remove-output \
    --assume-yes-for-downloads \
    --include-package=moonlight \
    --include-package=fastapi \
    --include-package=uvicorn \
    --include-package=jinja2 \
    --include-package=playwright \
    --include-package=ollama \
    --include-package=PIL \
    --include-package=numpy \
    --include-package=yaml \
    --include-package=click \
    --include-package=rich \
    --include-package-data=moonlight \
    --include-package-data=playwright \
    --noinclude-dlls=libgtk-3.so.0 \
    --quiet \
    app.py

mv "$OUT_DIR/app.dist" "$OUT_DIR/runtime"

# ---------- bundle resources ----------
mkdir -p "$OUT_DIR"/{scenarios,baselines,auth-state,logs,runs}
cp -r config.yaml LICENSE OPERATIONS.md "$OUT_DIR/" 2>/dev/null || true
cp src/moonlight/templates "$OUT_DIR/runtime/moonlight/" -r 2>/dev/null || true
cp -r src/moonlight/web/templates "$OUT_DIR/runtime/moonlight/web/" 2>/dev/null || true
cp -r src/moonlight/web/static "$OUT_DIR/runtime/moonlight/web/" 2>/dev/null || true

# Bundle Playwright Chromium so the binary doesn't need internet on the tester's box
PW_CACHE="${PLAYWRIGHT_BROWSERS_PATH:-$HOME/.cache/ms-playwright}"
if [[ -d "$PW_CACHE" ]]; then
    cp -r "$PW_CACHE" "$OUT_DIR/playwright-browsers"
    echo "[build] bundled Playwright browsers"
fi

# Launcher script that sets PLAYWRIGHT_BROWSERS_PATH + MOONLIGHT_HOME
cat > "$OUT_DIR/start.sh" <<'LAUNCH'
#!/usr/bin/env bash
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export MOONLIGHT_HOME="$HERE"
export PLAYWRIGHT_BROWSERS_PATH="$HERE/playwright-browsers"
exec "$HERE/runtime/moonlight" "$@"
LAUNCH
chmod +x "$OUT_DIR/start.sh"

echo "[build] OK → $OUT_DIR/"
echo "[build] size: $(du -sh "$OUT_DIR" | cut -f1)"
echo "[build] zip with: cd dist && zip -r moonlight-linux-$BUILD_DATE.zip moonlight-linux-$BUILD_DATE"

# Restore source build sentinel so dev work resumes unrestricted
cat > src/moonlight/_buildinfo.py <<'EOF'
"""Build-time stamped constants. Generated by the build pipeline."""
BUILD_DATE = "SOURCE_BUILD"
BUILD_ID = "source-build"
VERSION = "0.1.0"
REVOCATION_REPO = ""
REVOCATION_FILE = "revoked.json"
REVOCATION_PAT = ""
EOF
echo "[build] _buildinfo.py reset to SOURCE_BUILD for dev work"
